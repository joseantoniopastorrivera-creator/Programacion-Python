# Listas
listaVacia = []
listaNumeros = [1, 2, 3, 4]
listaMixta = ["Hola", 2, False, 3.14]
print("Lista vacía: ", listaVacia)
print("Lista de números: ", listaNumeros)
print("Lista mixta: ", listaMixta)
print("Primer elemento de la lista de números: ", listaNumeros[0])
print("Último elemento de la lista mixta: ", listaMixta[-1])
print("Penúltimo elemento de la lista mixta: ", listaMixta[-2])
print("Intervalo dentro de la lista mixta: ", listaMixta[0:3])
print("Intervalo dentro de la lista mixta: ", listaMixta[1:3])
listaMixta[2] = True
print("Lista mixta modificada: ", listaMixta)